"""0.4 (integrator follow-up to DOCS_AUDIT R3-C3): `rnplens selftest` and `rnplens diagnose selftest` still run
Diagnose's contract checks and example regression on bundled data, but their display must not show Diagnose's
interpretation statements while Diagnose is BLOCKED. The frozen component is unchanged and still prints them
(positive control); checks, verdicts, exit codes and the --out self-test record are unchanged."""
import json
import os
import re
import subprocess
import sys

import pytest

from rnplens import geometry_block as GB
from rnpbench_diagnose import diagnose as D

COMPONENT = "import sys; from rnpbench import cli; sys.exit(cli.main(sys.argv[1:]))"
TOOLKIT = "import sys; from rnpbench import toolkit; sys.exit(toolkit.main(sys.argv[1:]))"
# a statement as the frozen Diagnose prints it: banded text, or the unavailable form
STATEMENT = re.compile(r"across the (candidates|engines): disagreement|relative to the frozen development reference"
                       r"|development targets\)|^\s*(protein_side|rna_side): not available", re.M)
ENV = dict(os.environ, MPLBACKEND="Agg")


def rn(*args):
    return subprocess.run([sys.executable, "-m", "rnplens", *args], capture_output=True, text=True, env=ENV)


def comp(*args, toolkit=False):
    return subprocess.run([sys.executable, "-c", TOOLKIT if toolkit else COMPONENT, *args], capture_output=True,
                          text=True, env=ENV)


def checks(text):
    """The check and verdict lines (everything a self-test decides), without the statement lines."""
    return [l for l in text.splitlines() if re.match(r"\s+diagnose\.", l) or l.startswith(("PASS", "FAIL"))]


def test_every_frozen_statement_wording_is_masked():
    """Texts generated by the frozen statement function for every mode, side and band, plus the unavailable form
    and the applicability warning the frozen command prints."""
    lines = []
    for mode, which in sorted(D.EVIDENCE):
        axis = D.AXIS_FOR[which]
        for v in (0.05, 0.6, 1.5, 4.0, 40.0):                 # spans the bands of the frozen reference
            s = D.statement(mode, which, {axis: v})
            assert s["available"]
            lines.append("  " + s["text"])
        lines.append("  %s: not available" % D.statement(mode, which, {"refused": "x"})["statement"])
    lines.append("  WARNING: outside the validated applicability domain (accepted with --allow-outside-validated-domain)")
    assert len({l for l in lines}) >= 10 and all(STATEMENT.search(l) or "WARNING" in l for l in lines)
    for l in lines:
        m = GB.mask_diagnose_statements(l)
        assert m.strip().startswith(GB.DIAGNOSE_MASK) and not STATEMENT.search(m) and not re.search(r"\d", m), (l, m)
    keep = ["  diagnose.contract_checks           ok    n_checks=18, n_failed=0",
            "PASS: RNPLens Diagnose self-test (profile portable)",
            "wrote report.html, report.json to ./x/diagnose_out", "== diagnose", ""]
    assert [GB.mask_diagnose_statements(l) for l in keep] == keep


@pytest.mark.parametrize("profile", ["portable", "reference"])
def test_diagnose_selftest_masks_statements_and_keeps_checks_verdict_and_exit(profile):
    c = comp("diagnose", "selftest", "--profile", profile)
    assert STATEMENT.search(c.stdout), "positive control: the frozen component itself prints the statements"
    r = rn("diagnose", "selftest", "--profile", profile)
    assert r.returncode == c.returncode
    assert not STATEMENT.search(r.stdout + r.stderr) and "disagreement" not in r.stdout + r.stderr
    assert r.stdout.count(GB.DIAGNOSE_MASK) == len([l for l in c.stdout.splitlines() if STATEMENT.search(l)]) == 2
    assert checks(r.stdout) == checks(c.stdout) and checks(r.stdout)
    assert len(r.stdout.splitlines()) == len(c.stdout.splitlines())        # one masked line per statement line


def test_diagnose_selftest_out_record_is_the_frozen_record(tmp_path):
    c = comp("diagnose", "selftest", "--out", str(tmp_path / "c"))
    r = rn("diagnose", "selftest", "--out", str(tmp_path / "r"))
    assert r.returncode == c.returncode == 0
    assert os.listdir(tmp_path / "r") == os.listdir(tmp_path / "c") == ["selftest_record.json"]
    rec = open(tmp_path / "r" / "selftest_record.json").read()
    assert json.loads(rec) == json.loads(open(tmp_path / "c" / "selftest_record.json").read())
    assert not STATEMENT.search(rec)
    again = rn("diagnose", "selftest", "--out", str(tmp_path / "r"))          # never overwritten, as before
    assert again.returncode == comp("diagnose", "selftest", "--out", str(tmp_path / "c")).returncode != 0


def test_toolkit_selftest_masks_diagnose_statements():
    c = comp("selftest", toolkit=True)
    assert STATEMENT.search(c.stdout), "positive control: the frozen toolkit self-test prints the statements"
    r = rn("selftest")
    assert r.returncode == c.returncode == 0 and "PASS: rnplens selftest" in r.stdout
    assert not STATEMENT.search(r.stdout + r.stderr) and r.stdout.count(GB.DIAGNOSE_MASK) == 2
    assert checks(r.stdout) == checks(c.stdout)


def test_diagnose_selftest_help_is_unchanged():
    assert rn("diagnose", "selftest", "--help").stdout == comp("diagnose", "selftest", "--help").stdout
