"""Build records/v04_integration/CLEAN_INSTALL_LINUX.md from a clean_install_linux.sh folder (logs and results.tsv
only): python make_record.py CI_ROOT OUT_MD [--section TITLE]
--section writes the same content one heading level down, under '## TITLE', for appending to the existing record."""
import json
import os
import re
import sys

CI, OUT = os.path.realpath(sys.argv[1]), sys.argv[2]
SECTION = sys.argv[sys.argv.index("--section") + 1] if "--section" in sys.argv else None


def log(name):
    p = os.path.join(CI, "logs", name + ".log")
    return open(p, encoding="utf-8", errors="replace").read() if os.path.exists(p) else None


def short(s):
    return s.replace(CI, "<CI>")


def body(name):
    t = log(name)
    return "" if t is None else short("\n".join(t.splitlines()[1:]))


def first_json(text):
    i = text.find("{")
    try:
        return json.JSONDecoder().raw_decode(text[i:])[0] if i >= 0 else None
    except ValueError:
        return None


