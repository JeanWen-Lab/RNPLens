def synthetic_no_admissible_candidate():
    """Exercise the NO_ADMISSIBLE_CANDIDATE_SCORED branch on a CONSTRUCTED input.

    Not a pilot observation and never reported as one: a protein-only model and an RNA-only reference are
    written to a scratch directory by extracting chains from real files, so every candidate pairs protein
    with nucleic and the Part A rule must reject all of them, leaving an explicit failure with no value.
    """
    import glob as _g
    import tempfile
    ms = sorted(_g.glob(R + "/outputs/rnpbench/pilot/boltz/exec_A/*/boltz_results_*/predictions/*/"
                        "*_model_0.pdb"))
    if not ms:
        return None
    src = ms[0]
    t = os.path.basename(src).split("_model_0")[0].upper()
    ref = R + "/outputs/rnpbench/pilot/references/%s.cif" % t
    if not os.path.exists(ref):
        return None
    d = tempfile.mkdtemp(prefix="synth_noadm_")
    cls_m, cls_n = polymer_class(src), polymer_class(ref)
    prot = [c for c, v in cls_m.items() if v[0] == "protein"]
    nuc = [c for c, v in cls_n.items() if v[0] == "nucleic"]
    if not prot or not nuc:
        return None
    sm = gemmi.read_structure(src); sm.setup_entities()
    sn = gemmi.read_structure(ref); sn.setup_entities()
    for st, keep in ((sm, set(prot)), (sn, set(nuc))):
        for model in st:
            for ch in [c.name for c in model]:
                if ch not in keep:
                    model.remove_chain(ch)
    mp = d + "/protein_only_model.cif"; nt = d + "/rna_only_reference.cif"
    sm.setup_entities(); sn.setup_entities()
    sm.make_mmcif_document().write_file(mp)
    sn.make_mmcif_document().write_file(nt)
    try:
        v = score_v2(mp, nt, 0)
    except (Exception, SystemExit) as e:
        return {"status": "PROBE_FAILED", "exception": "%s: %s" % (type(e).__name__, str(e)[:120])}
    return {"constructed_from": t, "model_chains_kept": prot, "reference_chains_kept": nuc,
            "status": v["status"], "n_candidates": v["n_candidates_from_the_metric"],
            "n_inadmissible": v["n_inadmissible_cross_polymer"], "n_scored": v["n_scored"],
            "no_numerical_substitute_emitted": v.get("dockq") is None}


def stage_regression():
    A = json.load(open(REP + "/jpf_rnpbench_evaluator_minimal_cases.json"))
    P = {(r.get("engine"), r.get("target")): r for r in A["per_case"]}
    ctrl = A["control"]
