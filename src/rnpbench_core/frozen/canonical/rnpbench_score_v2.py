def polymer_class(path):
    """Chain id -> polymer class from the structure file. 'unknown' is never grounds for rejection."""
    st = gemmi.read_structure(path)
    st.setup_entities()
    out = {}
    for ch in st[0]:
        try:
            pt = str(ch.get_polymer().check_polymer_type())
        except Exception:
            pt = "untyped"
        cls = ("nucleic" if ("Rna" in pt or "Dna" in pt)
               else "protein" if "Peptide" in pt else "unknown")
        out[ch.name] = (cls, pt)
    return out


def parse_output(blob):
    """Both quantities, by the metric's own line formats.

    reported_dockq -- token after the 'DockQ' label on the line STARTING with 'DockQ ', which is exactly
                      what the frozen project scorer records.
    total_dockq    -- the aggregate the metric itself maximises over candidates.
    """
    reported = total = None
    n_interfaces = None
    for ln in blob.split("\n"):
        s = ln.strip()
        if s.startswith("DockQ ") and reported is None:
            parts = s.split()
            try:
                reported = float(parts[1])
            except (IndexError, ValueError):
                reported = None
        if s.startswith("Total DockQ over") and total is None:
            try:
                n_interfaces = int(s.split("over")[1].split()[0])
                total = float(s.split(":")[1].split()[0])
            except (IndexError, ValueError):
                total = None
    return reported, total, n_interfaces


def candidate_set(model, native, tol):
    """The metric's OWN candidates, via its own call chain read from main()."""
    initial_mapping, mchains, nchains = D.format_mapping(None, None)
    ms = D.load_PDB(model, chains=mchains, small_molecule=None)
    ns = D.load_PDB(native, chains=nchains, small_molecule=None)
    mchains = [c.id for c in ms] if not mchains else mchains
    nchains = [c.id for c in ns] if not nchains else nchains
    m_combo = [x for x in mchains if x not in initial_mapping.values()]
    n_combo = [x for x in nchains if x not in initial_mapping.keys()]
    clusters, reverse_map = D.group_chains(ms, ns, m_combo, n_combo, tol)
    maps = list(D.get_all_chain_maps(clusters, initial_mapping, reverse_map, m_combo, n_combo))
    return maps, mchains, nchains, clusters


def to_pairs(cmap, mchains, nchains):
    """(model, native) pairs. Direction resolved from chain-id membership, never assumed."""
    ks, vs = set(cmap.keys()), set(cmap.values())
    m, n = set(mchains), set(nchains)
    if ks <= n and vs <= m and not (ks <= m and vs <= n):
        return sorted((v, k2) for k2, v in cmap.items()), "keys_are_native"
    if ks <= m and vs <= n and not (ks <= n and vs <= m):
        return sorted((k2, v) for k2, v in cmap.items()), "keys_are_model"
    # ids overlap on both sides: use the metric's own formatter, which defines the direction itself
    s = D.format_mapping_string(cmap)
    a, b = s.split(":")
    return sorted(zip(list(a), list(b))), "resolved_by_the_metrics_own_formatter"


def admissibility(pairs, cls_m, cls_n):
    """Part A. Reject only a determined protein/nucleic mismatch; never reject on unknown."""
    bad = []
    for a, b in pairs:
        ca = cls_m.get(a, ("unknown", "absent"))[0]
        cb = cls_n.get(b, ("unknown", "absent"))[0]
        if ca in ("protein", "nucleic") and cb in ("protein", "nucleic") and ca != cb:
            bad.append({"model_chain": a, "model_class": ca, "native_chain": b, "native_class": cb})
    if bad:
        return "INADMISSIBLE_CROSS_POLYMER", bad
    return "ADMISSIBLE", []


def run_candidate(model, native, mstr, tol):
    cmd = [DOCKQ, model, native, "--short", "--allowed_mismatches", str(tol), "--mapping", mstr]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return {"outcome": "UNRESOLVED_EXCEPTION", "exception": "TIMEOUT",
                "reported_dockq": None, "total_dockq": None, "n_interfaces": None, "exit_code": None}
    blob = (r.stdout or "") + (r.stderr or "")
    rep, tot, ni = parse_output(blob)
    if rep is not None and tot is not None:
        return {"outcome": "SCORED", "reported_dockq": rep, "total_dockq": tot,
                "n_interfaces": ni, "exit_code": r.returncode}
    exc = None
    for ln in reversed(blob.strip().split("\n")):
        if ("Error" in ln or "error" in ln) and ":" in ln:
            exc = ln.strip()[:180]
            break
    return {"outcome": "UNRESOLVED_EXCEPTION",
            "exception": exc or "NO_VALUE_AND_NO_EXCEPTION_LINE",
            "reported_dockq": None, "total_dockq": None, "n_interfaces": ni,
            "exit_code": r.returncode, "output_tail": blob[-260:]}


def evaluate_in_process(ms, ns, cmap):
    """Evaluate ONE candidate by handing the metric's own candidate object back to it, unmodified.

    WHY v2.1 REPLACED THE PINNED-COMMAND-LINE ROUTE. v2.0 evaluated each candidate by re-invoking the
    command line with --mapping. The uniform rescore then LOST 30 established AF3 values (1RMV, 4C9D,
    6NY2; 5 samples x 2 executions each) that the unpinned automatic run still produces. The cause is not
    the admissibility rule -- admissibility rejected nothing on those rows -- but the pinned path itself:
    passing the mapping THE AUTOMATIC RUN ITSELF REPORTED, e.g. --mapping AB:AC on 4C9D which the
    automatic search selected and scored 0.804, exits 1 with KeyError. So --mapping is unreliable on
    inputs the automatic path handles, and any evaluation strategy built on it inherits that.

    This route avoids it entirely: structures are loaded ONCE without chain restriction (mirroring what
    main() does), and each candidate map generated by get_all_chain_maps is passed straight into
    run_on_all_native_interfaces. No mapping string is re-parsed, no direction is reconstructed, and no
    chain-restricted reload happens. Exceptions remain catchable per candidate, so the Part B taxonomy is
    unchanged. Verified to reproduce the frozen values on all three lost targets: 4C9D 0.8043 (frozen
    0.804), 1RMV 0.0397 (0.04), 6NY2 0.3373 (0.337).
    """
    r = D.run_on_all_native_interfaces(ms, ns, chain_map=cmap)
    per, tot = (r[0], r[1]) if isinstance(r, tuple) else (r, None)
    first = None
    if isinstance(per, dict) and per:
        # the metric's OWN iteration order, which is the order its --short output prints interfaces in;
        # the frozen project scorer reads the FIRST such line. sorted() would impose a different order.
        v0 = per[next(iter(per))]
        if isinstance(v0, dict):
            first = v0.get("DockQ")
    return {"reported_dockq": (None if first is None else round(float(first), 3)),
            "total_dockq": (None if tot is None else float(tot)),
            "n_interfaces": (len(per) if hasattr(per, "__len__") else None),
            "interface_keys": (sorted(per) if isinstance(per, dict) else None)}


def score_v2(model, native, tol=0):
    """One target-sample pair under the corrected admissibility and failure handling."""
    cls_m, cls_n = polymer_class(model), polymer_class(native)
    # THE METRIC CALLS sys.exit() ON SOME INPUTS -- found by this file's own synthetic probe, which
    # triggered "For chains ['R'] no identical corresponding chain was found" and terminated the whole
    # harness, because SystemExit does not derive from Exception. An in-process evaluator MUST trap it,
    # and an input the metric refuses outright is an input-level outcome, not a candidate-level one.
    try:
        initial_mapping, mch, nch = D.format_mapping(None, None)
        ms = D.load_PDB(model, chains=mch, small_molecule=None)
        ns = D.load_PDB(native, chains=nch, small_molecule=None)
        mchains = [c.id for c in ms]
        nchains = [c.id for c in ns]
        m_combo = [x for x in mchains if x not in initial_mapping.values()]
        n_combo = [x for x in nchains if x not in initial_mapping.keys()]
        clusters, reverse_map = D.group_chains(ms, ns, m_combo, n_combo, tol)
        maps = list(D.get_all_chain_maps(clusters, initial_mapping, reverse_map, m_combo, n_combo))
    except (Exception, SystemExit) as e:
        return {"scorer_version": SCORER_VERSION, "model": model, "native": native,
                "allowed_mismatches": tol,
                "status": "METRIC_REFUSED_THE_INPUT_BEFORE_ANY_CANDIDATE",
                "refusal": "%s: %s" % (type(e).__name__, str(e)[:160]),
                "dockq": None, "n_candidates_from_the_metric": 0,
                "n_inadmissible_cross_polymer": 0, "n_scored": 0, "n_unresolved_exception": 0,
                "candidates": [],
                "NO_NUMERICAL_SUBSTITUTE": ("the metric declined the input itself; this is neither an "
                                            "admissibility rejection nor a candidate failure")}
    cands, dirs = [], set()
    for cm in maps:
        pairs, direction = to_pairs(cm, mchains, nchains)
        dirs.add(direction)
        verdict, bad = admissibility(pairs, cls_m, cls_n)
        mstr = D.format_mapping_string(cm)
        row = {"mapping": mstr, "pairs": pairs,
               "class_pairs": ["%s->%s" % (cls_m.get(a, ("unknown",))[0], cls_n.get(b, ("unknown",))[0])
                               for a, b in pairs]}
        if verdict == "INADMISSIBLE_CROSS_POLYMER":
            row.update({"outcome": "INADMISSIBLE_CROSS_POLYMER",
                        "reason": "pairs chains of different determined polymer class",
                        "offending_pairs": bad,
                        "reported_dockq": None, "total_dockq": None})
        else:
            try:
                got = evaluate_in_process(ms, ns, cm)
                if got["n_interfaces"] == 0:
                    # V2.2 CLASSIFICATION CORRECTION. v2.1 filed this under UNRESOLVED_EXCEPTION with the
                    # note COMPLETED_WITHOUT_A_VALUE, which conflated two different things and inflated
                    # the unresolved population. Characterised directly: the metric RETURNS ({}, 0) here --
                    # an empty interface dict with total 0 -- and raises nothing. Its own command line says
                    # "Could not find interfaces in the native model" for the same pinned mapping. So the
                    # candidate is not an unexplained failure: the metric completed and reported that this
                    # pairing has no native interface, which is the expected outcome for a symmetry-copy
                    # pairing whose chains are not in contact.
                    #
                    # AND IT CARRIES A CERTIFICATE. The selection objective is the MAXIMUM total over
                    # candidates. A candidate whose total is 0 cannot exceed a candidate whose total is
                    # positive, so such candidates provably cannot change the selected result whenever at
                    # least one candidate scores. That is a valid certificate, not an assumption -- and it
                    # is exactly why these rows must not be left blocking official status. When NO
                    # candidate has a positive total the row is genuinely unscoreable and is reported so.
                    row.update({"outcome": "NO_NATIVE_INTERFACE_UNDER_THIS_MAPPING",
                                "metric_returned": "empty interface dict, total 0, no exception raised",
                                "certifiably_non_maximal_when_any_candidate_scores": True, **got})
                elif got["reported_dockq"] is None or got["total_dockq"] is None:
                    row.update({"outcome": "UNRESOLVED_EXCEPTION",
                                "exception": "COMPLETED_WITH_INTERFACES_BUT_NO_PARSEABLE_VALUE", **got})
                else:
                    row.update({"outcome": "SCORED", **got})
            except (Exception, SystemExit) as e:
                # SystemExit included deliberately: the metric exits rather than raising on some inputs,
                # and a candidate must never be able to terminate the harness
                row.update({"outcome": "UNRESOLVED_EXCEPTION",
                            "exception": "%s: %s" % (type(e).__name__, str(e)[:160]),
                            "reported_dockq": None, "total_dockq": None})
        cands.append(row)
    scored = [c for c in cands if c["outcome"] == "SCORED"]
    unresolved = [c for c in cands if c["outcome"] == "UNRESOLVED_EXCEPTION"]
    no_iface = [c for c in cands if c["outcome"] == "NO_NATIVE_INTERFACE_UNDER_THIS_MAPPING"]
    inadmissible = [c for c in cands if c["outcome"] == "INADMISSIBLE_CROSS_POLYMER"]
    unevaluable = [c for c in cands if c["outcome"] == "UNEVALUABLE_DECLARED"]
    out = {"scorer_version": SCORER_VERSION, "model": model, "native": native,
           "allowed_mismatches": tol,
           "evaluation_route": "in_process_metric_api_with_its_own_candidate_objects",
           "chain_clusters_from_the_metric": ({str(k2): list(v) for k2, v in clusters.items()}
                                              if isinstance(clusters, dict) else [list(c) for c in clusters]),
           "direction_resolution": sorted(dirs),
           "n_candidates_from_the_metric": len(cands),
           "n_inadmissible_cross_polymer": len(inadmissible),
           "n_admissible": len(cands) - len(inadmissible),
           "n_scored": len(scored), "n_unresolved_exception": len(unresolved),
           "n_no_native_interface": len(no_iface),
           "n_unevaluable_declared": len(unevaluable),
           "candidates": cands}
    if scored:
        # selection by the METRIC'S OWN objective: maximum total over native interfaces
        best = max(scored, key=lambda c: (c["total_dockq"], c["mapping"]))
        out["selected_mapping"] = best["mapping"]
        # the mapping STRING is normalised (pairs sorted by model chain) while the metric emits pairs in
        # its own order, so 'BA:RP' and 'AB:PR' denote the SAME pairing. Equality must therefore be tested
        # on the pair set, never on the rendered string.
        out["selected_pairs"] = [list(p) for p in best["pairs"]]
        out["selected_total_dockq"] = best["total_dockq"]
        out["dockq"] = best["reported_dockq"]
        out["n_interfaces"] = best["n_interfaces"]
        # a no-interface candidate is EVALUATED, not unresolved, and is certifiably non-maximal here
        out["status"] = ("SCORED_ALL_ADMISSIBLE_EVALUATED" if not unresolved
                         else "SCORED_WITH_UNRESOLVED_ADMISSIBLE_CANDIDATES")
        out["certificate_over_no_interface_candidates"] = (
            "%d admissible candidate(s) returned no native interface (total 0) and cannot exceed the "
            "selected total %.6f; they are evaluated and non-maximal, not unresolved"
            % (len(no_iface), best["total_dockq"])) if no_iface else None
        if unresolved:
            out["CAVEAT"] = ("this value is the best SUCCESSFULLY EVALUATED candidate, not established as "
                             "the intended maximum: %d admissible candidate(s) raised an unexplained "
                             "exception and any of them could have scored higher" % len(unresolved))
    else:
        out["status"] = "NO_ADMISSIBLE_CANDIDATE_SCORED"
        out["dockq"] = None
        out["NO_NUMERICAL_SUBSTITUTE"] = ("no admissible candidate produced a value; no zero, no "
                                          "imputation and no partial aggregate is emitted")
    return out


def pairs_of(mstr):
    """Parse a rendered mapping string into an order-independent set of (model, native) pairs."""
    if not mstr or ":" not in mstr:
        return None
    a, b = mstr.split(":")
    if len(a) != len(b):
        return None
    return frozenset(zip(list(a), list(b)))


def automatic_run(model, native, tol=0):
    """The metric's OWN unpinned automatic invocation -- the parallel candidate path.

    This is what produced the frozen values, so it is the reference for equivalence AND it is the
    serial-versus-parallel check: v2 evaluates candidates serially in separate processes, the automatic
    run may evaluate them in child processes.
    """
    cmd = [DOCKQ, model, native, "--short", "--allowed_mismatches", str(tol)]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return {"reported_dockq": None, "total_dockq": None, "mapping": None, "exit_code": None}
    blob = (r.stdout or "") + (r.stderr or "")
    rep, tot, ni = parse_output(blob)
    mp = None
    for ln in blob.split("\n"):
        if "model:native mapping" in ln:
            mp = ln.split("with")[1].split("model:native")[0].strip()
            break
    return {"reported_dockq": rep, "total_dockq": tot, "mapping": mp, "exit_code": r.returncode,
            "n_interfaces": ni}


def order_invariance(model, native, tol=0, seed=20260908):
    """Selection must not depend on the order candidates are evaluated in."""
    import random
    base = score_v2(model, native, tol)
    if base["status"] == "NO_ADMISSIBLE_CANDIDATE_SCORED":
        return {"checked": False, "reason": "no scored candidate to order"}
    scored = [c for c in base["candidates"] if c["outcome"] == "SCORED"]
    rnd = random.Random(seed)
    perm = scored[:]
    rnd.shuffle(perm)
    best = max(perm, key=lambda c: (c["total_dockq"], c["mapping"]))
    return {"checked": True,
            "selection_invariant": best["mapping"] == base["selected_mapping"]
                                   and best["reported_dockq"] == base["dockq"],
            "selected": base["selected_mapping"], "under_permutation": best["mapping"]}


