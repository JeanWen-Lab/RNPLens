#!/usr/bin/env python3
"""RNPBENCH_SCORE_V2 -- bounded, versioned mapping-admissibility and candidate-failure correction.

SCOPE, RULED. Two parts, and neither replaces the metric's existing correspondence rules:

  PART A -- ADMISSIBILITY. The candidate set is the METRIC'S OWN, generated by its own functions
      (format_mapping -> load_PDB -> group_chains -> get_all_chain_maps), so its sequence-correspondence
      rules, the frozen entity-restricted reference, and legitimate copy/symmetry alternatives are all
      preserved. The correction REMOVES candidates that pair chains of different polymer class, using
      polymer type from the structure files. Chain length is NOT used. A chain whose polymer type cannot
      be determined is NEVER rejected -- unknown is not incompatible, and rejecting on unknown
      information would be a silent new exclusion.
      This is recorded as a MAPPING-ADMISSIBILITY CORRECTION. It is NOT claimed to leave the candidate
      set literally unchanged: it is strictly a restriction, and the restriction is itemised per pair.
      Polymer compatibility is NOT claimed sufficient: two chains can both be protein, or both RNA, and
      still belong to different entities or correspond inadequately. Those cases remain the metric's own
      correspondence problem and are untouched here.

  PART B -- CANDIDATE FAILURE HANDLING that does not conceal evaluator errors. Every candidate gets one
      of four outcomes, and the three failure kinds are NEVER merged:
        INADMISSIBLE_CROSS_POLYMER   excluded by the Part A rule, with its reason recorded
        SCORED                       enters the selection objective unchanged
        UNEVALUABLE_DECLARED         a documented policy class -- DEFINED BUT EMPTY at v2.0, because no
                                     failure mode has yet been established as legitimately unevaluable.
                                     Nothing is swept into it to make the output look clean.
        UNRESOLVED_EXCEPTION         an apparently admissible candidate raised an unexplained exception.
                                     Kept VISIBLE. A crash does not prove the candidate was invalid, so
                                     skipping it may hide the best mapping.
      Consequently the selection status distinguishes:
        SCORED_ALL_ADMISSIBLE_EVALUATED              every admissible candidate scored
        SCORED_WITH_UNRESOLVED_ADMISSIBLE_CANDIDATES a value exists but is best-SUCCESSFULLY-evaluated,
                                                     not established as the intended maximum
        NO_ADMISSIBLE_CANDIDATE_SCORED               explicit failure, NO numerical substitute
      No failed candidate is scored as zero. No failed interface is dropped from an aggregate.

THE SELECTION OBJECTIVE IS THE METRIC'S OWN. DockQ selects the candidate maximising the TOTAL over native
interfaces, whereas the frozen project scorer REPORTS the per-interface value from the line starting
"DockQ " (deliberately: reading the "Total" line once produced DockQ=1.0 for every target, because the
token after that label is the interface count). Both are therefore parsed here: the total selects, the
per-interface value is reported, so previously-clean cases keep their recorded component value.

THE INSTALLED PACKAGE IS NOT MODIFIED. Candidates are evaluated by invoking the metric's command line once
per pinned candidate, which also isolates a crashing candidate to its own process instead of aborting the
run. Pinning takes the metric's single-job branch, so serial-versus-parallel equivalence is not assumed --
it is a required regression check below.
"""
