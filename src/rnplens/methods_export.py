class Missing(Exception):
    """A record field the template needs is absent: the sentence is omitted and listed."""


class NotApplicable(Missing):
    """The records show the sentence does not apply (e.g. one run only): omitted, listed as not applicable."""


class ExportError(Exception):
    pass


def _esc(k):
    return str(k).replace("~", "~0").replace("/", "~1")


class Records:
    """Named record documents and a log of the fields each template reads."""

    def __init__(self, docs, paths, roots):
        self.docs, self.paths, self.roots = docs, paths, roots   # name -> parsed JSON; name -> abs path; name -> evidence root
        self.log = None

    def has(self, name):
        return self.docs.get(name) is not None

    def get(self, name, pointer):
        doc = self.docs.get(name)
        if doc is None:
            raise Missing("%s (record not available)" % name)
        obj = doc
        for part in [p for p in pointer.split("/")[1:]] if pointer not in ("", "/") else []:
            part = part.replace("~1", "/").replace("~0", "~")
            try:
                obj = obj[int(part)] if isinstance(obj, list) else obj[part]
            except (KeyError, IndexError, ValueError, TypeError):
                raise Missing("%s#%s" % (name, pointer))
        if self.log is not None:
            self.log.append((name, pointer, obj))
        return obj

    def names(self, prefix):
        return sorted(n for n in self.docs if n.startswith(prefix) and self.docs[n] is not None)


def load_records(analysis, project=None, run_dirs=()):
    analysis = os.path.abspath(analysis)
    if not os.path.exists(os.path.join(analysis, "summary.json")):
        raise ExportError("%s has no summary.json: give a directory written by 'rnplens analyse'" % analysis)
    paths = {"summary": os.path.join(analysis, "summary.json"),
             "report_result": os.path.join(analysis, "report", "result.json"),
             "report_run": os.path.join(analysis, "report", "rnplens_run.json")}
    if project is None:
        try:
            rec = json.load(open(paths["report_run"], encoding="utf-8"))
            for x in rec.get("inputs", []):
                if x["path"].endswith("report_contract.json"):
                    project = os.path.dirname(x["path"])
        except (OSError, ValueError):
            project = None
    if project:
        paths["manifest"] = os.path.join(os.path.abspath(project), "manifest.json")
    for p in sorted(glob.glob(os.path.join(analysis, "region_*", "region.json"))):
        paths["region:" + os.path.basename(os.path.dirname(p))] = p
    for p in sorted(glob.glob(os.path.join(analysis, "groups", "**", "*.json"), recursive=True)):
        paths["group:" + os.path.relpath(p, os.path.join(analysis, "groups")).replace(os.sep, "/")] = p
    for i, r in enumerate(run_dirs or []):
        paths["run_record:%d" % i] = os.path.join(os.path.abspath(r), "run_record.json")
        paths["plan:%d" % i] = os.path.join(os.path.abspath(r), "plan.json")
    docs = {}
    for n, p in paths.items():
        try:
            docs[n] = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None
        except ValueError:
            docs[n] = None
    if docs.get("manifest"):                             # recorded structure files: resolved and hash-verified
        from . import portability as PT
        docs["manifest"] = PT.check_manifest(os.path.dirname(paths["manifest"]), docs["manifest"], "read", "export-methods")[0]
    roots = {n: (os.path.dirname(paths[n]) if n.startswith(("run_record", "plan")) else analysis) for n in paths}
    return Records(docs, paths, roots)


# ---------------------------------------------------------------- helpers for templates
def _plural(n, one, many=None):
    return "%d %s" % (n, one if n == 1 else (many or one + "s"))


def _join(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def _keys_checked(R, name, pointer, against_name, against_pointer):
    """Keys of a record dict, required to equal an independent list in the records (so a removed key is a missing
    field, never a silently shorter sentence)."""
    d = R.get(name, pointer)
    want = R.get(against_name, against_pointer)
    want = sorted(x["engine"] if isinstance(x, dict) else x for x in want)
    if not isinstance(d, dict) or sorted(d) != want:
        raise Missing("%s#%s (keys do not match %s#%s)" % (name, pointer, against_name, against_pointer))
    return sorted(d)


def _runs(R):
    rows = R.get("manifest", "/runs")
    return [(R.get("manifest", "/runs/%d/run" % i), R.get("manifest", "/runs/%d/engine" % i),
             R.get("manifest", "/runs/%d/n_structures" % i)) for i in range(len(rows))]


ENGINE_NAMES = {"BOLTZ2": "Boltz-2", "CHAI1": "Chai-1", "AF3": "AlphaFold 3", "RF3": "RoseTTAFold 3", "RF2NA": "RoseTTAFoldNA",
                "OTHER": "an unnamed engine"}


