def t_structures(R):
    n = R.get("manifest", "/counts/included")
    pl = R.get("manifest", "/construct/protein_length")
    rl = R.get("manifest", "/construct/rna_length")
    return ("A total of %s of one protein-RNA construct (protein, %d residues; RNA, %d nucleotides) were analysed."
            % (_plural(n, "predicted structure"), pl, rl))


def _included_per_run(R):
    """Structures each run contributes (verdict INCLUDED), keyed by (run, engine); their total must equal
    manifest /counts/included (an independent field), so a removed structure entry omits the sentence."""
    st = R.get("manifest", "/structures")
    inc = {}
    for i in range(len(st)):
        if R.get("manifest", "/structures/%d/verdict" % i) == "INCLUDED":
            k = (R.get("manifest", "/structures/%d/run" % i), R.get("manifest", "/structures/%d/engine" % i))
            inc[k] = inc.get(k, 0) + 1
    if sum(inc.values()) != R.get("manifest", "/counts/included"):
        raise Missing("manifest#/structures (included structures do not match manifest#/counts/included)")
    return inc


def t_runs(R):
    # runs[].n_structures counts every structure file found in a run, including files excluded at import; the
    # number a run contributes to the analysis is its INCLUDED structures (QA workflow-replay, 2026-10-17)
    runs = _runs(R)
    inc = _included_per_run(R)
    engines = sorted({e for _, e, _ in runs})

    def one(r, e, n):
        k = inc.get((r, e), 0)
        txt = "%s, %s" % (r, _plural(k, "structure"))
        if k != n:
            txt += " (%s found, %d excluded at import)" % (_plural(n, "structure file"), n - k)
        return txt
    return "The structures came from %s of %s: %s." % (
        _plural(len(runs), "prediction run"), _join([ENGINE_NAMES.get(e, e) for e in engines]),
        "; ".join(one(r, e, n) for r, e, n in runs))


def t_designation(R):
    rows = R.get("manifest", "/runs")
    rules = [(R.get("manifest", "/runs/%d/run" % i), R.get("manifest", "/runs/%d/designated_rule" % i)) for i in range(len(rows))]
    return "In each run the engine-designated structure was identified by the rule recorded at import (%s)." % "; ".join(
        "%s: %s" % x for x in rules)


def t_inputs(R):
    st = R.get("manifest", "/structures")
    srcs = sorted({str(R.get("manifest", "/structures/%d/engine_source" % i)) for i in range(len(st))})
    if not all(R.get("manifest", "/structures/%d/original_sha256" % i) for i in range(len(st))):
        raise Missing("manifest#/structures/*/original_sha256 (empty)")
    return ("Structure files were assigned to engines at import (engine label source: %s), and every file was recorded "
            "by its SHA-256 checksum." % _join(srcs))


def t_chains(R):
    st = R.get("manifest", "/structures")
    status = {}
    for i in range(len(st)):
        for j in range(len(R.get("manifest", "/structures/%d/chains" % i))):
            s = R.get("manifest", "/structures/%d/chains/%d/status" % (i, j))
            status[s] = status.get(s, 0) + 1
    return ("Each chain was compared with the declared construct sequences (chain status: %s)."
            % ", ".join("%s %d" % kv for kv in sorted(status.items())))


def t_derived(R):
    st = R.get("manifest", "/structures")
    der = [i for i in range(len(st)) if R.get("manifest", "/structures/%d/derived" % i)]
    if not der:
        return "No structure required a derived copy; the original files were analysed."
    tr = sorted({t for i in der for t in R.get("manifest", "/structures/%d/derived/transformations" % i)})
    for i in der:
        R.get("manifest", "/structures/%d/derived/from_sha256" % i)
    return "%s analysed through derived copies (%s); each copy records the checksum of its original." % (
        _plural(len(der), "structure was", "structures were"), "; ".join(tr))


def t_excluded(R):
    x = R.get("manifest", "/counts/excluded")
    if x == 0:
        return "No candidate structure file was excluded at import."
    st = R.get("manifest", "/structures")
    verd = {}
    for i in range(len(st)):
        v = R.get("manifest", "/structures/%d/verdict" % i)
        if v != "INCLUDED":
            verd[v] = verd.get(v, 0) + 1
    return "%s excluded at import (%s)." % (_plural(x, "candidate structure file was", "candidate structure files were"),
                                           ", ".join("%s %d" % kv for kv in sorted(verd.items())))


