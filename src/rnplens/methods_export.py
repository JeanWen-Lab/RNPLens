def templates(R):
    T = [("structures", "Structures analysed", t_structures), ("runs", "Structures analysed", t_runs),
         ("designation", "Structures analysed", t_designation),
         ("inputs", "Input and construct identification", t_inputs), ("chains", "Input and construct identification", t_chains),
         ("derived", "Input and construct identification", t_derived), ("excluded", "Input and construct identification", t_excluded),
         ("version", "Software", t_version), ("software", "Software", t_software),
         ("contacts", "Measures", t_contacts), ("counts", "Measures", t_counts), ("repeat", "Measures", t_repeat),
         ("run_repeat", "Measures", t_run_repeat), ("diagnose", "Measures", t_diagnose)]
    for n in R.names("region:"):
        T.append(("%s.listing" % n, "Measures", lambda R, n=n: t_region(R, n)))
        T.append(("%s.agreement" % n, "Agreement between runs", lambda R, n=n: t_region_agreement(R, n)))
        T.append(("%s.missing" % n, "Missing outputs and unresolved positions", lambda R, n=n: t_region_missing(R, n)))
    T += [("ineligible", "Missing outputs and unresolved positions", t_ineligible),
          ("not_computed", "Missing outputs and unresolved positions", t_not_computed),
          ("reference", "Reference-based and reference-free measures", t_reference),
          ("withheld", "Reference-based and reference-free measures", t_withheld),
          ("descriptive", "Reference-based and reference-free measures", t_descriptive)]
    for i in sorted(int(n.split(":")[1]) for n in R.names("run_record:")):
        T.append(("assistant:%d" % i, "Assistant", lambda R, i=i: t_assistant(R, i)))
    return T


SECTIONS = ["Structures analysed", "Input and construct identification", "Software", "Measures", "Agreement between runs",
            "Missing outputs and unresolved positions", "Reference-based and reference-free measures", "Assistant"]


def generate(R):
    """-> (sentences, omitted). Each sentence: id, section, text, sources [{record, pointer, evidence_id, value}]."""
    sents, omitted = [], []
    for sid, sec, fn in templates(R):
        R.log = []
        try:
            text = fn(R)
        except Missing as ex:
            omitted.append({"id": sid, "section": sec, "missing": str(ex),
                            "kind": "not_applicable" if isinstance(ex, NotApplicable) else "field_missing"})
            continue
        finally:
            log, R.log = R.log, None
        srcs, seen = [], set()
        for name, ptr, val in log:
            if (name, ptr) in seen:
                continue
            seen.add((name, ptr))
            rel = os.path.relpath(R.paths[name], R.roots[name]).replace(os.sep, "/")
            srcs.append({"record": name, "file": rel, "pointer": ptr, "evidence_id": pv.evidence_id(rel, ptr),
                         "value": val if isinstance(val, (str, int, float, bool)) or val is None else "(structured)"})
        sents.append({"id": sid, "section": sec, "text": text, "sources": srcs})
    return sents, omitted


def render_md(sents, omitted):
    L = ["# Methods (draft)", "", "> " + DRAFT_NOTE, ""]
    for sec in SECTIONS:
        ss = [s for s in sents if s["section"] == sec]
        if ss:
            L += ["## " + sec, "", " ".join(s["text"] for s in ss), ""]
    miss = [o for o in omitted if o["kind"] == "field_missing"]
    if miss:
        L += ["## Not stated (record field missing)", ""] + ["- %s: %s" % (o["id"], o["missing"]) for o in miss] + [""]
    L += ["_Sentence sources: methods_sources.json. Inputs, outputs, versions and commands: provenance_manifest.json._", ""]
    return "\n".join(L)


def render_txt(sents, omitted):
    L = ["METHODS (DRAFT)", "", DRAFT_NOTE, ""]
    for sec in SECTIONS:
        ss = [s for s in sents if s["section"] == sec]
        if ss:
            L += [sec.upper(), " ".join(s["text"] for s in ss), ""]
    miss = [o for o in omitted if o["kind"] == "field_missing"]
    if miss:
        L += ["NOT STATED (record field missing)"] + ["  %s: %s" % (o["id"], o["missing"]) for o in miss] + [""]
    return "\n".join(L)


def provenance_manifest(R, analysis):
    """All input and output files with SHA-256, versions and commands, from the records."""
    analysis = os.path.abspath(analysis)
    inputs, seen = [], set()

    def add(path, sha, role, recorded=None):
        if path and path not in seen:
            seen.add(path)
            ok = os.path.exists(path)
            now = pv.sha256_file(path) if ok else None
            inputs.append({"path": path, "role": role, "sha256": now, "recorded_sha256": recorded,
                           "matches_record": (now == recorded) if recorded else None, "present": ok})
    man = R.docs.get("manifest")
    if man:
        add(R.paths["manifest"], None, "project manifest")
        proj = os.path.dirname(R.paths["manifest"])
        for f in ("construct_protein.fasta", "construct_rna.fasta", "report_contract.json"):
            add(os.path.join(proj, f), None, "project file")
        for s in man.get("structures", []):
            add(s.get("path"), None, "original structure file (%s, %s)" % (s.get("id"), s.get("verdict")), s.get("original_sha256"))
            if s.get("used_path") != s.get("path"):
                add(s.get("used_path"), None, "derived structure file (%s)" % s.get("id"), s.get("used_sha256"))
    for n in sorted(R.paths):
        if n.startswith(("run_record", "plan")) and R.docs.get(n) is not None:
            add(R.paths[n], None, "assistant record")
    outputs = []
    for dp, dn, fn in os.walk(analysis):
        dn[:] = sorted(x for x in dn if x not in ("methods", "explain"))
        for f in sorted(fn):
            p = os.path.join(dp, f)
            outputs.append({"file": os.path.relpath(p, analysis).replace(os.sep, "/"), "sha256": pv.sha256_file(p)})
    commands = []
    for p in sorted(glob.glob(os.path.join(analysis, "**", "rnplens_run.json"), recursive=True)):
        try:
            rec = json.load(open(p, encoding="utf-8"))
            commands.append({"source": os.path.relpath(p, analysis).replace(os.sep, "/"), "command": rec.get("command"),
                             "rnplens_version": rec.get("rnplens_version"), "created_utc": rec.get("created_utc")})
        except (OSError, ValueError):
            pass
    log = os.path.join(analysis, "commands.log")
    if os.path.exists(log):
        for i, line in enumerate(open(log, encoding="utf-8")):
            if line.startswith("$ "):
                commands.append({"source": "commands.log:%d" % (i + 1), "command": line[2:].strip()})
    for n in R.names("region:") + R.names("group:"):
        pb = R.docs[n].get("provenance") if isinstance(R.docs[n], dict) else None
        if pb and pb.get("command"):
            commands.append({"source": os.path.relpath(R.paths[n], analysis).replace(os.sep, "/"), "command": pb["command"],
                             "rnplens_version": pb.get("rnplens_version")})
    versions = {"rnplens_export": __version__}
    S = R.docs.get("summary") or {}
    if S.get("rnplens_version"):
        versions["rnplens_analysis"] = S["rnplens_version"]
    rr = R.docs.get("report_result") or {}
    if rr.get("package_version"):
        versions["report_component"] = rr["package_version"]
    if rr.get("environment"):
        versions["report_environment"] = rr["environment"]
    run = R.docs.get("report_run") or {}
    if run.get("implementation"):
        versions["implementation"] = run["implementation"]
    for n in R.names("run_record:"):
        versions["assistant:" + n.split(":")[1]] = R.docs[n].get("assistant_version")
    return {"inputs": inputs, "outputs": outputs, "commands": commands, "versions": versions}


def build(analysis, project=None, run_dirs=(), records=None):
    R = records or load_records(analysis, project, run_dirs)
    sents, omitted = generate(R)
    md, txt = render_md(sents, omitted), render_txt(sents, omitted)
    used = sorted({R.paths[s["record"]] for x in sents for s in x["sources"]})
    prov = pv.block(KIND, [p for p in used if os.path.exists(p)], DEFINITION, {"run_dirs": [os.path.abspath(r) for r in run_dirs or []]})
    src = {"provenance": prov, "draft_note": DRAFT_NOTE, "sentences": sents, "omitted": omitted,
           "fixed_text": [{"text": DRAFT_NOTE, "source": "rnplens.methods_export.DRAFT_NOTE (fixed draft marker)"}],
           "llm_used": False}
    pm = {"provenance": prov, "manifest": provenance_manifest(R, analysis)}
    return md, txt, src, pm


def audit(sents):
    from .trace import wording_audit
    return wording_audit(" ".join(s["text"] for s in sents))


def run(analysis, project=None, run_dirs=(), out=None):
    md, txt, src, pm = build(analysis, project, run_dirs)
    bad = audit(src["sentences"])
    out = out or os.path.join(analysis, "methods")
    if bad:
        pv.atomic_write_text(os.path.join(out, "WORDING_AUDIT_FAILED.txt"), "\n".join(bad) + "\n")
        return 1, out
    pv.atomic_write_text(os.path.join(out, "methods.md"), md)
    pv.atomic_write_text(os.path.join(out, "methods.txt"), txt)
    pv.atomic_write_json(os.path.join(out, "methods_sources.json"), src)
    pv.atomic_write_json(os.path.join(out, "provenance_manifest.json"), pm)
    return 0, out


def capability_run(analysis, project=None, run_dir=None, **_):
    try:
        code, out = run(analysis, project, [run_dir] if run_dir else [])
    except ExportError as ex:
        return {"status": "REFUSED", "outputs": [], "message": str(ex)}
    if code:
        return {"status": "FAILED", "outputs": [], "message": "wording audit failed; see %s" % out}
    return {"status": "OK", "outputs": [os.path.join(out, f) for f in ("methods.md", "methods.txt", "methods_sources.json",
                                                                       "provenance_manifest.json")],
            "message": open(os.path.join(out, "methods.txt")).read(), "limits": CAPABILITIES[0]["limits"]}


def main(argv):
    import argparse
    ap = argparse.ArgumentParser(prog="rnplens export-methods", description="Write a Methods draft (Markdown and plain "
                                 "text) and a provenance manifest from execution records only; each sentence lists the "
                                 "record fields it was built from. No language model; no citations are generated.")
    ap.add_argument("analysis", help="analysis directory written by 'rnplens analyse'")
    ap.add_argument("--project", help="project directory (default: inferred from report/rnplens_run.json)")
    ap.add_argument("--run-dir", action="append", default=[], help="assistant run directory to describe (repeatable)")
    ap.add_argument("--out", help="output directory (default: ANALYSIS/methods)")
    a = ap.parse_args(argv)
    try:
        code, out = run(a.analysis, a.project, a.run_dir, a.out)
    except ExportError as ex:
        print("rnplens export-methods: refused: %s" % ex, file=sys.stderr)
        return 2
    if code:
        print("rnplens export-methods: wording audit failed; see %s" % os.path.join(out, "WORDING_AUDIT_FAILED.txt"), file=sys.stderr)
        return 1
    print(open(os.path.join(out, "methods.txt"), encoding="utf-8").read())
    print("  written: %s" % os.path.abspath(out))
    return 0
