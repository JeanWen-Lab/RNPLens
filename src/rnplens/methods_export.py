"""``rnplens export-methods``: a deterministic Methods draft and a provenance manifest, from execution records only.

Every sentence is produced by a template keyed to record fields. Templates read records only through
``Records.get(file, pointer)``, which logs each field it returns; the logged fields are that sentence's sources
(``methods_sources.json``). A template whose field is absent raises ``Missing`` and the sentence is omitted, and the
omission is listed, so removing a field removes the sentence. Nothing is invented: no condition, version,
statistic or citation that is not in a record. No language model is used. The text is marked as a draft for
author review.

Records read (when present): PROJECT/manifest.json; ANALYSIS/summary.json, report/result.json,
report/rnplens_run.json, region_*/region.json, groups/**.json (provenance blocks); assistant run_record.json and
plan.json. Outputs: ANALYSIS/methods/methods.md, methods.txt, methods_sources.json, provenance_manifest.json.
"""
